SELECT DISTINCT M1.OUTBOUND_DATE
      ,TO_CHAR(TO_DATE(M1.OUTBOUND_DATE, 'YYYY-MM-DD'), 'DY') AS DY
  FROM LO_OUT_M M1
       JOIN LO_OUT_D M2 ON M2.INVOICE_NO = M1.INVOICE_NO
 WHERE M1.OUTBOUND_DATE BETWEEN TO_CHAR(ADD_MONTHS(TO_DATE(:OUT_DATE, 'YYYYMMDD'), -1), 'YYYYMMDD') AND :OUT_DATE
--   AND M2.ORDER_QTY IS NULL
 ORDER BY M1.OUTBOUND_DATE
;


















