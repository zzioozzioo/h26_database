SELECT SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'MM'), '01', M2.ORDER_QTY)) AS M01
      ,SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'MM'), '02', M2.ORDER_QTY)) AS M02
      ,SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'MM'), '03', M2.ORDER_QTY)) AS M03
      ,SUM(CASE WHEN TO_CHAR(M1.OUTBOUND_DATE, 'MM') IN ('01', '02', '03') THEN M2.ORDER_QTY END) AS Q1
      ,SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'MM'), '04', M2.ORDER_QTY)) AS M04
      ,SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'MM'), '05', M2.ORDER_QTY)) AS M05
      ,SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'MM'), '06', M2.ORDER_QTY)) AS M06
      ,SUM(CASE WHEN TO_CHAR(M1.OUTBOUND_DATE, 'MM') IN ('04', '05', '06') THEN M2.ORDER_QTY END) AS Q2
      ,SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'MM'), '07', M2.ORDER_QTY)) AS M07
      ,SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'MM'), '08', M2.ORDER_QTY)) AS M08
      ,SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'MM'), '09', M2.ORDER_QTY)) AS M09
      ,SUM(CASE WHEN TO_CHAR(M1.OUTBOUND_DATE, 'MM') IN ('07', '08', '09') THEN M2.ORDER_QTY END) AS Q3
      ,SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'MM'), '10', M2.ORDER_QTY)) AS M10
      ,SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'MM'), '11', M2.ORDER_QTY)) AS M11
      ,SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'MM'), '12', M2.ORDER_QTY)) AS M12
      ,SUM(CASE WHEN TO_CHAR(M1.OUTBOUND_DATE, 'MM') IN ('10', '11', '12') THEN M2.ORDER_QTY END) AS Q4
  FROM LO_OUT_M M1 
       JOIN LO_OUT_D M2 ON M2.INVOICE_NO = M1.INVOICE_NO
 WHERE M1.OUTBOUND_DATE BETWEEN TO_DATE(:OUT_DATE || '0101', 'YYYYMMDD') 
                            AND TO_DATE(:OUT_DATE || '1231', 'YYYYMMDD')
;

