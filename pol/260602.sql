SELECT M1.INVOICE_NO, M1.OUTBOUND_DATE, M1.OUT_TYPE_DIV, M2.LINE_NO, M2.ITEM_CD, M2.ITEM_NM, M2.ORDER_QTY
      ,NVL(C2.CODE_NM, 'Failed..') AS TEMP_NM
      ,C3.CODE_NM AS OUT_TYPE_NM
  FROM LO_OUT_M M1
       JOIN LO_OUT_D M2 ON M1.INVOICE_NO = M2.INVOICE_NO
       JOIN CM_ITEM C1  ON C1.ITEM_CD    = M2.ITEM_CD
  LEFT JOIN CS_CODE C2  ON C2.CODE_GRP   = 'LDIV011'
                       AND C2.CODE_CD    = M1.TEMP_DIV
       JOIN CS_CODE C3  ON C3.CODE_GRP   = 'LDIV03'
                       AND C3.CODE_CD       = M1.OUT_TYPE_DIV 
 WHERE M1.INVOICE_NO IN ('346724703834', '346724722535', '346724717915')
 ORDER BY M1.INVOICE_NO, M2.LINE_NO
;

--4)
SELECT OUT_DATE, NVL(QTY, 0) AS QTY
  FROM (
        SELECT TRUNC(TO_DATE(:OUTBOUND_DATE), 'MM') + NO-1 AS OUT_DATE
          FROM CS_NO  
         WHERE NO <= TO_DATE(:OUTBOUND_DATE, 'YYYY-MM-DD') - TRUNC(TO_DATE(:OUTBOUND_DATE, 'YYYY-MM-DD'), 'MM') + 1
       ) T1
  LEFT JOIN (
             SELECT OUTBOUND_DATE, SUM(ORDER_QTY) AS QTY
               FROM LO_OUT_M M1
                    JOIN LO_OUT_D M2 ON M1.INVOICE_NO = M2.INVOICE_NO
              WHERE OUTBOUND_DATE BETWEEN TRUNC(TO_DATE(:OUTBOUND_DATE, 'YYYY-MM-DD'), 'MM') AND TO_DATE(:OUTBOUND_DATE, 'YYYY-MM-DD')
              GROUP BY OUTBOUND_DATE
              ORDER BY OUTBOUND_DATE
            ) T2 ON T1.OUT_DATE = T2.OUTBOUND_DATE
 ORDER BY OUT_DATE
;

