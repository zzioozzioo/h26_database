SELECT CASE WHEN OUTBOUND_DATE = LAG(OUTBOUND_DATE) OVER(ORDER BY "일자별 수량 합계" DESC, ORDER_QTY DESC) THEN ' ' 
            ELSE TO_CHAR(OUTBOUND_DATE, 'YY/MM/DD')
       END AS "출고일자"
      ,OUTBOUND_BATCH
      ,ORDER_QTY
      ,"일자별 수량 합계"
      ,"일자별 수량 합계 랭킹"
      ,"전체 랭킹"
  FROM (
        SELECT OUTBOUND_DATE
              ,OUTBOUND_BATCH
              ,ORDER_QTY
              ,DAILY_SUM_QTY AS "일자별 수량 합계"
              ,DENSE_RANK() OVER(ORDER BY DAILY_SUM_QTY DESC) AS "일자별 수량 합계 랭킹"
              ,RANK() OVER(ORDER BY ORDER_QTY DESC)           AS "전체 랭킹"
          FROM (
                SELECT M1.OUTBOUND_DATE, M1.OUTBOUND_BATCH,
                            SUM(M2.ORDER_QTY) AS ORDER_QTY,
                            SUM(SUM(M2.ORDER_QTY)) OVER(PARTITION BY M1.OUTBOUND_DATE) AS DAILY_SUM_QTY
                  FROM LO_OUT_M M1
                       JOIN LO_OUT_D M2 ON M2.INVOICE_NO = M1.INVOICE_NO
                 WHERE M1.OUTBOUND_DATE BETWEEN '2019-09-03' AND '2019-09-10'
                   AND M1.OUT_TYPE_DIV = 'M11'
                 GROUP BY M1.OUTBOUND_DATE, M1.OUTBOUND_BATCH 
               )
       )
 ORDER BY "일자별 수량 합계" DESC, ORDER_QTY DESC, OUTBOUND_BATCH
;

