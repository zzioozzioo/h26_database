SELECT OUTBOUND_DATE, SUM(ORDER_QTY) AS SUM_QTY
  FROM LO_OUT_M M1
       JOIN LO_OUT_D M2 ON M2.INVOICE_NO = M1.INVOICE_NO
 WHERE M1.OUTBOUND_DATE BETWEEN TO_DATE(:OUT_DATE || '01', 'YYYY-MM-DD') AND LAST_DAY(TO_DATE(:OUT_DATE || '01', 'YYYY-MM-DD'))
 GROUP BY M1.OUTBOUND_DATE
 ORDER BY SUM_QTY DESC
;

