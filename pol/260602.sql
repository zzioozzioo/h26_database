SELECT CASE WHEN RNK <= 5 THEN TO_CHAR(OUTBOUND_DATE, 'YYYY-MM-DD')
            ELSE '기타'
       END AS OUTBOUND_DATE
      ,SUM(ORDER_QTY) AS SUM_QTY
      ,MIN(RNK) AS RNK
      ,SUM(RATE) AS RATE
  FROM (
        SELECT M1.OUTBOUND_DATE, SUM(M2.ORDER_QTY) AS ORDER_QTY
              ,ROW_NUMBER() OVER(ORDER BY SUM(M2.ORDER_QTY)) AS RNK
              ,ROUND(RATIO_TO_REPORT(SUM(M2.ORDER_QTY)) OVER() * 100, 3) AS RATE
          FROM LO_OUT_M M1
               JOIN LO_OUT_D M2 ON M2.INVOICE_NO = M1.INVOICE_NO
         WHERE M1.OUTBOUND_DATE BETWEEN '2019-09-01' AND '2019-09-15'
         GROUP BY M1.OUTBOUND_DATE
       )
 GROUP BY CASE WHEN RNK <= 5 THEN TO_CHAR(OUTBOUND_DATE) ELSE '기타' END
 ORDER BY RNK
;
 
