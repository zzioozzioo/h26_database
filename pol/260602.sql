  FROM LO_OUT_M M1
       JOIN LO_OUT_D M2 ON M1.INVOICE_NO = M2.INVOICE_NO
       JOIN CM_ITEM C1 ON C1.ITEM_CD = M2.ITEM_CD
 WHERE OUTBOUND_DATE BETWEEN '2019-09-03' AND '2019-09-10'
   AND OUT_BOX_DIV = 'D5'
 GROUP BY M2.ITEM_CD, C1.ITEM_NM
 ORDER BY ORDER_QTY DESC
;

