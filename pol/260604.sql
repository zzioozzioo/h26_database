SELECT SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'D'), '1', M2.ORDER_QTY, 0)) AS SUN
      ,SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'D'), '2', M2.ORDER_QTY, 0)) AS MON
      ,SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'D'), '3', M2.ORDER_QTY, 0)) AS TUE
      ,SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'D'), '4', M2.ORDER_QTY, 0)) AS WED
      ,SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'D'), '5', M2.ORDER_QTY, 0)) AS THU
      ,SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'D'), '6', M2.ORDER_QTY, 0)) AS FRI
      ,SUM(DECODE(TO_CHAR(M1.OUTBOUND_DATE, 'D'), '7', M2.ORDER_QTY, 0)) AS SAT
  FROM LO_OUT_M M1 
       JOIN LO_OUT_D M2 ON M2.INVOICE_NO = M1.INVOICE_NO
 WHERE M1.OUTBOUND_DATE BETWEEN TO_DATE(:OUT_DATE || '01', 'YYYYMMDD') 
                            AND LAST_DAY(TO_DATE(:OUT_DATE || '01', 'YYYYMMDD'))
;

SELECT TO_CHAR(M1.OUTBOUND_DATE, 'DAY') AS DAY
      ,SUM(ORDER_QTY) AS ORDER_QTY
  FROM LO_OUT_M M1 
       JOIN LO_OUT_D M2 ON M2.INVOICE_NO = M1.INVOICE_NO
 WHERE M1.OUTBOUND_DATE BETWEEN TO_DATE(:OUT_DATE || '01', 'YYYYMMDD') AND LAST_DAY(TO_DATE(:OUT_DATE || '01', 'YYYYMMDD'))
 GROUP BY TO_CHAR(M1.OUTBOUND_DATE, 'DAY')
         ,TO_CHAR(M1.OUTBOUND_DATE, 'D') -- D로 정렬해야 하는 이유:
 ORDER BY TO_CHAR(M1.OUTBOUND_DATE, 'D') -- ORDER BY에는 GROUP BY, WHERE, 집계함수 제외한 SELECT 컬럼에 존재하는 컬럼만 올 수 있음
;

